export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { interactive?: boolean; glowing?: boolean }
>(({ className, interactive = false, glowing = false, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-2xl text-slate-100",
      interactive ? "glass-card" : "glass-card-static",
      glowing && "border-indigo-500/30 glow-indigo",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

